#!/usr/bin/perl

use strict;
use warnings;
use File::Path qw(make_path);
use Getopt::Long qw(GetOptions);
use JSON::PP;

my ($seed, $output, $kind) = (undef, undef, 'both');
GetOptions('seed=s' => \$seed, 'output=s' => \$output, 'kind=s' => \$kind) && !@ARGV
    or die "usage: generate_tests.pl --seed UINT32 --output DIRECTORY [--kind cfg|abi|both]\n";
die "An unsigned 32-bit decimal seed and an output directory are required\n"
    unless defined($seed) && $seed =~ /^\d+$/ && $seed <= 0xffffffff && defined($output);
die "Unknown generator $kind\n" unless $kind =~ /^(cfg|abi|both)$/;
make_path($output);
my $state = 0 + $seed;
my $json = JSON::PP->new->canonical->pretty;

# All intermediate products fit exactly in a Perl 64-bit integer. Mask at
# each target-width operation, independently of the generated code's types.
sub next_word { $state = ($state * 1664525 + 1013904223) & 0xffffffff; return $state; }
sub write_file {
    my ($name, $text) = @_;
    open(my $file, '>:raw', "$output/$name") or die "$output/$name: $!\n";
    print {$file} $text;
    close($file) or die "$output/$name: $!\n";
}
sub write_expect { write_file($_[0] . '.wasm-expect', $json->encode($_[1])); }

sub cfg_oracle {
    my ($x, $y, $add, $mix, $shift, $count, $mode) = @_;
    for my $i (0 .. $count - 1) {
        my $choice = ($i + $mode) & 3;
        my $value = $choice == 0 ? $x + $y + $add : $choice == 1 ? $x ^ $mix
            : $choice == 2 ? ((($x << $shift) | ($x >> (32 - $shift))) ^ $y) : $y - $x;
        ($x, $y) = ($y, $value & 0xffffffff);
    }
    return $x ^ $y;
}

sub generate_cfg {
    $state = 0 + $seed;
    my $name = "300-generated-cfg-$seed";
    my $source = "# Generated by pa37/scripts/generate_tests.pl, seed $seed.\ntarget wasm32 1\n\n";
    my @sequence;
    for my $case (0 .. 3) {
        my ($a, $b, $add, $mix) = map { next_word() } 1 .. 4;
        # Include zero, all bits set and the sign bit alongside random values.
        $a = (0, 0xffffffff, 0x80000000, $a)[$case];
        my $shift = 1 + next_word() % 31;
        my $right = 32 - $shift;
        $source .= <<"LOWIR";
function \@kernel$case(%count : i32, %mode : i32) -> i32 {
  block ^entry:
    jump ^header
  block ^header:
    %x = phi i32 [^entry: $a, ^latch: %y]
    %y = phi i32 [^entry: $b, ^latch: %next]
    %i = phi i32 [^entry: 0, ^latch: %next_i]
    %more = cmp ult i32 %i, %count
    branch %more, ^body, ^exit
  block ^body:
    %which = binary add i32 %i, %mode
    %choice = binary and i32 %which, 3
    switch %choice, ^subtract, 0:^add, 1:^xor, 2:^rotate
LOWIR
        my @blocks = (
            "  block ^add:\n    %sum = binary add i32 %x, %y\n    %added = binary add i32 %sum, $add\n    jump ^latch\n",
            "  block ^xor:\n    %mixed = binary xor i32 %x, $mix\n    jump ^latch\n",
            "  block ^rotate:\n    %left = binary shl i32 %x, $shift\n    %right = binary ushr i32 %x, $right\n" .
                "    %rotated = binary or i32 %left, %right\n    %combined = binary xor i32 %rotated, %y\n    jump ^latch\n",
            "  block ^subtract:\n    %difference = binary sub i32 %y, %x\n    jump ^latch\n");
        for (my $i = $#blocks; $i > 0; --$i) {
            my $j = next_word() % ($i + 1);
            @blocks[$i, $j] = @blocks[$j, $i];
        }
        $source .= join('', @blocks) . <<'LOWIR';
  block ^latch:
    %next = phi i32 [^add: %added, ^xor: %mixed, ^rotate: %combined, ^subtract: %difference]
    %next_i = binary add i32 %i, 1
    jump ^header
  block ^exit:
    %result = binary xor i32 %x, %y
    return i32 %result
}

LOWIR
        for my $count (0, 1, 2, 7, 17) {
            for my $mode (0 .. 3) {
                push @sequence, {export => "kernel$case", args => [$count, $mode],
                    result => '' . cfg_oracle($a, $b, $add, $mix, $shift, $count, $mode)};
            }
        }
    }
    $source =~ s/\n+\z/\n/;
    write_file("$name.t", $source);
    write_expect($name, {sequences => [\@sequence], object_mutations => ['magic', 'version', 'truncate']});
}

sub scalar_value {
    my ($type, $value) = @_;
    return $value & 255 if $type eq 'unsigned char';
    return $value & 65535 if $type eq 'unsigned short';
    return $value & 0xffffffff;
}

sub generate_abi {
    $state = 0 + $seed;
    my $name = "400-generated-abi-$seed";
    my $header = "// Generated by pa37/scripts/generate_tests.pl, seed $seed.\n";
    my $caller = "#include \"$name.t.h\"\n";
    my $callee = $caller;
    my @sequence;
    my @types = ('unsigned char', 'unsigned short', 'unsigned', 'unsigned long long', 'float', 'double');
    for my $case (0 .. 5) {
        my $fields = $case < 2 ? 1 : 2 + next_word() % 4;
        my $alignment = $case == 1 || $case == 5 ? 'alignas(32) ' : '';
        my (@types_used, @values, @increments);
        $header .= "struct ${alignment}Record$case {\n";
        for my $field (0 .. $fields - 1) {
            my $type = $types[($case + $field + next_word()) % @types];
            push @types_used, $type;
            push @values, 128 + next_word() % 512;
            push @increments, 1 + next_word() % 17;
            $header .= "  $type field$field;\n";
        }
        $header .= "};\nextern \"C\" Record$case transform$case(Record$case, unsigned);\n";
        $callee .= "extern \"C\" Record$case transform$case(Record$case value, unsigned delta) {\n";
        for my $field (0 .. $fields - 1) {
            $callee .= "  value.field$field = static_cast<$types_used[$field]>(value.field$field + delta + $increments[$field]);\n";
        }
        $callee .= "  return value;\n}\n";
        my @initializers = map { "static_cast<$types_used[$_]>($values[$_])" } 0 .. $fields - 1;
        $caller .= "extern \"C\" unsigned observe$case(unsigned delta) {\n" .
            "  Record$case original = {" . join(', ', @initializers) . "};\n" .
            "  Record$case (*volatile target)(Record$case, unsigned) = transform$case;\n" .
            "  Record$case changed = target(original, delta);\n";
        my @terms;
        for my $field (0 .. $fields - 1) {
            push @terms, "static_cast<unsigned>(changed.field$field) * " . (2 * $field + 1) . "u",
                "static_cast<unsigned>(original.field$field) * " . (2 * $field + 2) . "u";
        }
        $caller .= '  return ' . join(' + ', @terms) . ";\n}\n";
        for my $delta (0, 1, 17, 255) {
            my $result = 0;
            for my $field (0 .. $fields - 1) {
                my $before = scalar_value($types_used[$field], $values[$field]);
                my $after = scalar_value($types_used[$field], $before + $delta + $increments[$field]);
                $result += $after * (2 * $field + 1) + $before * (2 * $field + 2);
            }
            push @sequence, {export => "observe$case", args => [$delta], result => '' . ($result & 0xffffffff)};
        }
    }
    write_file("$name.t", $caller);
    write_file("$name.t.1", $callee);
    write_file("$name.t.h", $header);
    write_expect($name, {source => JSON::PP::true, units => ["$name.t.1"],
        llvm_interop => JSON::PP::true, sequences => [\@sequence]});
}

generate_cfg() if $kind eq 'cfg' || $kind eq 'both';
generate_abi() if $kind eq 'abi' || $kind eq 'both';
